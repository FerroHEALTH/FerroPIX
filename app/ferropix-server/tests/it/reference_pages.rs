//! The book's generated reference: the command-line page, rendered from the
//! `clap` definitions of `ferropix` and `ferropix-console`, and the table of
//! problem types on the problem types page, rendered from
//! [`ferropix_server::problem::Kind`].
//!
//! Each `the_book_holds_*` test fails when the committed text differs from
//! what the code renders; `write_the_reference_pages` (ignored, run with
//! `cargo nextest run -p ferropix-server --test it --run-ignored only
//! reference_pages`) writes both again. No specification governs the pages:
//! our own design.

use std::path::PathBuf;

use clap::{Command, CommandFactory as _};
use ferropix_server::problem::Kind;

/// The command-line page, relative to the workspace root.
const CLI_PAGE: &str = "website/book/src/reference/cli.md";

/// The problem types page, relative to the workspace root.
const PROBLEMS_PAGE: &str = "website/book/src/operate/problems.md";

/// The line that opens the generated table on the problem types page.
const TABLE_BEGIN: &str = "<!-- BEGIN @generated by the ferropix-server test reference_pages from problem::Kind. DO NOT EDIT. -->";

/// The line that closes it.
const TABLE_END: &str = "<!-- END @generated -->";

/// The help width, fixed so the page does not depend on the terminal.
const WIDTH: usize = 100;

/// Returns the path of `page` under the workspace root.
fn path(page: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(page)
}

/// Appends the section of `command`, reached as `path`, and of each visible
/// subcommand below it.
fn section(out: &mut String, path: &str, command: &mut Command) {
    let help = command.render_long_help().to_string();
    for piece in [
        "### `",
        path,
        "`\n\n```text\n",
        help.trim_end(),
        "\n```\n\n",
    ] {
        out.push_str(piece);
    }
    for sub in command
        .get_subcommands_mut()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
    {
        let below = [path, sub.get_name()].join(" ");
        section(out, &below, sub);
    }
}

/// Appends the sections of one binary under its heading.
fn binary(out: &mut String, heading: &str, command: Command) {
    let mut command = command.term_width(WIDTH).max_term_width(WIDTH);
    command.build();
    let name = command.get_name().to_owned();
    for piece in ["## ", heading, "\n\n"] {
        out.push_str(piece);
    }
    section(out, &name, &mut command);
}

// REUSE-IgnoreStart
/// Returns the command-line page the definitions render.
fn render_cli() -> String {
    let mut out = String::from(
        "<!-- @generated by the ferropix-server test reference_pages from the clap \
         definitions. DO NOT EDIT. -->\n\
         <!-- SPDX-FileCopyrightText: Cadasto B.V. -->\n\
         <!-- SPDX-License-Identifier: BUSL-1.1 -->\n\n\
         # Command-line reference\n\n\
         **Audience:** operators. Every command and option of the `ferropix` and\n\
         `ferropix-console` binaries, as `<binary> <command> --help` prints it.\n\
         [Configuration](../operate/configuration.md) describes the configuration\n\
         every command reads, and a refused configuration exits 78 (`EX_CONFIG`).\n\n\
         <!-- toc -->\n\n",
    );
    binary(&mut out, "The server", ferropix_server::cli::Cli::command());
    binary(
        &mut out,
        "The console",
        ferropix_console::cli::Cli::command(),
    );
    out.trim_end().to_owned() + "\n"
}
// REUSE-IgnoreEnd

/// Returns the table of problem types, between its two marker lines.
fn render_table() -> String {
    let mut out = String::from(TABLE_BEGIN);
    out.push_str("\n\n| Type | Status | Title |\n|---|---|---|\n");
    for kind in Kind::ALL {
        let (slug, title, status) = kind.definition();
        let row = format!(
            "| [`{slug}`](#{slug}) | `{}` | {title} |\n",
            status.as_u16()
        );
        out.push_str(&row);
    }
    out.push('\n');
    out.push_str(TABLE_END);
    out
}

/// Returns the problem types page with its generated table replaced by
/// `table`.
fn with_table(page: &str, table: &str) -> String {
    let begin = page
        .find(TABLE_BEGIN)
        .expect("the problem types page holds the table's opening marker");
    let end = page
        .find(TABLE_END)
        .expect("the problem types page holds the table's closing marker")
        + TABLE_END.len();
    assert!(begin < end, "the table's markers are in order");
    let (head, rest) = page.split_at(begin);
    let tail = rest.split_at(end - begin).1;
    [head, table, tail].concat()
}

#[test]
fn the_book_holds_the_current_cli_reference() {
    let committed = std::fs::read_to_string(path(CLI_PAGE)).expect("the CLI reference page");
    assert!(
        committed == render_cli(),
        "{CLI_PAGE} is out of date: run `cargo nextest run -p ferropix-server --test it \
         --run-ignored only reference_pages` and commit the page"
    );
}

#[test]
fn the_book_holds_the_current_problem_type_table() {
    let committed = std::fs::read_to_string(path(PROBLEMS_PAGE)).expect("the problem types page");
    assert!(
        committed == with_table(&committed, &render_table()),
        "the table of {PROBLEMS_PAGE} is out of date: run `cargo nextest run -p \
         ferropix-server --test it --run-ignored only reference_pages` and commit the page"
    );
}

#[test]
fn the_cli_reference_names_every_job() {
    let page = render_cli();
    for job in [
        "ferropix serve",
        "ferropix config check",
        "ferropix healthcheck",
        "ferropix db migrate",
        "ferropix db reseal",
        "ferropix matching estimate",
        "ferropix-console serve",
        "ferropix-console config check",
        "ferropix-console healthcheck",
    ] {
        assert!(page.contains(&format!("### `{job}`")), "{job}");
    }
}

#[test]
#[ignore = "writes the book pages; run on purpose after changing the CLI or a problem type"]
fn write_the_reference_pages() {
    std::fs::write(path(CLI_PAGE), render_cli()).expect("the CLI reference page is written");
    let page = std::fs::read_to_string(path(PROBLEMS_PAGE)).expect("the problem types page");
    std::fs::write(path(PROBLEMS_PAGE), with_table(&page, &render_table()))
        .expect("the problem types page is written");
}
